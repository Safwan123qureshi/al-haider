import { chromium } from "playwright-core";
const b = await chromium.launch({ headless: true, executablePath: "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe" });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.goto("http://localhost:4173/", { waitUntil: "networkidle", timeout: 60000 });
await p.waitForSelector(".menu-card");
await new Promise(r => setTimeout(r, 1500));
await p.screenshot({ path: "shot-hero.png" });
await p.evaluate(() => document.getElementById("menu")?.scrollIntoView({ behavior: "instant" }));
await new Promise(r => setTimeout(r, 1800));
const card = p.locator(".menu-card").first();
await card.hover({ position: { x: 120, y: 80 } });
await new Promise(r => setTimeout(r, 700));
await p.screenshot({ path: "shot-menu.png" });
await p.evaluate(() => document.getElementById("about")?.scrollIntoView({ behavior: "instant" }));
await new Promise(r => setTimeout(r, 1600));
await p.screenshot({ path: "shot-about.png" });
await p.setViewportSize({ width: 390, height: 844 });
await p.evaluate(() => window.scrollTo({ top: 0, behavior: "instant" }));
await new Promise(r => setTimeout(r, 1200));
await p.screenshot({ path: "shot-mobile.png" });
await b.close();
console.log("screenshots saved");
